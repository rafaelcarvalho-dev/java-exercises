public class L1Ex006 {
	
	public static void main (String[] args) {
		String primeiraSigla = "F01";
		
		String segundaSigla = "F02";
		
		String terceiraSigla = "F03";
		
		char escape = '\t';
		
		String primeiroCurso = "Lógica de Programação";
		
		String segundoCurso = "Linguagem de Programação";
		
		String terceiroCurso = "Programação Orientada a Objeto";
	
		System.out.println(primeiraSigla);
		System.out.println(escape + primeiroCurso);
	
		System.out.println(segundaSigla);
		System.out.println(escape + segundoCurso);
	
		System.out.println(terceiraSigla);
		System.out.println(escape + terceiroCurso);
	
	}
}

